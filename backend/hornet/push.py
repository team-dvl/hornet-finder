"""
Web Push: sending a notification to the devices of some users.

Identity towards the push services is VAPID (RFC 8292): a key pair per
environment, generated by `manage.py generate_vapid_keys` and set in the
environment (`VAPID_PUBLIC_KEY`, `VAPID_PRIVATE_KEY`, `VAPID_SUBJECT`). Without
them the feature is off (`enabled()` is false). The payload is encrypted for
each browser with the keys it gave when subscribing (RFC 8291).

Sending is done off the request: a push service answers in 0.1 to 1 s, and a
group may hold a few hundred devices.

The platform admins can hold back some kinds of notifications (`paused_kinds`):
the senders check it, and `_send_one` once more for what was already queued.

Retention (`purge_expired`, run by the scheduler): the history of sent
notifications for `PUSH_HISTORY_DAYS`, a device for `PUSH_DEVICE_IDLE_DAYS`
after the app was last opened on it.
"""

import datetime

import json
import logging
import re
import threading
from concurrent.futures import ThreadPoolExecutor

from django.conf import settings
from django.db import connection
from django.utils import timezone
from pywebpush import WebPushException, webpush

from .models import PlatformSettings, PushDelivery, PushNotification, PushSubscription

logger = logging.getLogger(__name__)

TTL_SECONDS = 24 * 3600  # how long a push service keeps a message for an unreachable device
TIMEOUT_SECONDS = 10
WORKERS = 8
GONE = (404, 410)  # the subscription no longer exists at the push service
# Not an HTTP code: the platform held the kind back after the delivery was queued
STATUS_PAUSED = 1


def enabled() -> bool:
    return bool(settings.VAPID_PUBLIC_KEY and settings.VAPID_PRIVATE_KEY)


def paused_kinds() -> set:
    """The kinds of notifications the platform admins hold back (`PlatformSettings`), read at each call."""
    return set(PlatformSettings.objects.values_list('paused_kinds', flat=True).first() or [])


def device_label(user_agent: str) -> str:
    """A short readable client from a user agent: "iOS · Safari", "Android · Chrome"."""
    ua = user_agent or ''
    if re.search(r'iPhone|iPad|iPod', ua):
        system = 'iOS'
    elif 'Android' in ua:
        system = 'Android'
    elif 'Windows' in ua:
        system = 'Windows'
    elif 'Mac OS X' in ua or 'Macintosh' in ua:
        system = 'macOS'
    elif 'Linux' in ua or 'X11' in ua:
        system = 'Linux'
    else:
        system = 'Appareil'
    # Order matters: Edge and Opera also say Chrome, Chrome also says Safari
    for token, browser in (('Edg', 'Edge'), ('OPR', 'Opera'), ('Firefox', 'Firefox'), ('FxiOS', 'Firefox'),
                           ('CriOS', 'Chrome'), ('Chrome', 'Chrome'), ('Safari', 'Safari')):
        if token in ua:
            return f'{system} · {browser}'
    return system


def _payload(delivery: PushDelivery, notification: PushNotification) -> str:
    return json.dumps({
        'id': str(delivery.id),
        'title': notification.title,
        'body': notification.body,
        'url': notification.url or '/',
        # A reminder repeated for the same trap replaces the previous one on screen
        'tag': f'{notification.kind}:{notification.trap_id}' if notification.trap_id else str(notification.id),
    }, ensure_ascii=False)


def _send_one(delivery_id) -> None:
    """Push one delivery and record the answer; drop a subscription that is gone."""
    delivery = PushDelivery.objects.select_related('notification', 'subscription').get(pk=delivery_id)
    subscription = delivery.subscription
    status, error = None, ''
    if delivery.notification.kind in paused_kinds():
        # Queued before the pause: the message is dropped, the device stays subscribed
        PushDelivery.objects.filter(pk=delivery_id).update(status=STATUS_PAUSED, error='paused by the platform',
                                                           sent_at=timezone.now())
        return
    if subscription is None:
        status, error = 410, 'subscription removed'
    else:
        try:
            webpush(
                subscription_info={'endpoint': subscription.endpoint,
                                   'keys': {'p256dh': subscription.p256dh, 'auth': subscription.auth}},
                data=_payload(delivery, delivery.notification),
                vapid_private_key=settings.VAPID_PRIVATE_KEY,
                vapid_claims={'sub': settings.VAPID_SUBJECT},  # fresh: webpush adds `aud` to it
                ttl=TTL_SECONDS,
                timeout=TIMEOUT_SECONDS,
            )
            status = 201
        except WebPushException as exc:
            status = exc.response.status_code if exc.response is not None else 0
            error = str(exc)[:200]
        except Exception as exc:  # network failure, bad key material: never block the others
            status, error = 0, f'{type(exc).__name__}: {exc}'[:200]
    PushDelivery.objects.filter(pk=delivery_id).update(status=status, error=error, sent_at=timezone.now())
    if status in GONE and subscription is not None:
        subscription.delete()
        logger.info("Push subscription %s removed (HTTP %s)", subscription.pk, status)
    elif status != 201:
        logger.warning("Push delivery %s failed: HTTP %s %s", delivery_id, status, error)


def _deliver(notification_id) -> None:
    """Send every pending delivery of a notification, a few at a time."""
    ids = list(PushDelivery.objects.filter(notification_id=notification_id, status__isnull=True)
               .values_list('id', flat=True))
    if settings.PUSH_SYNC:  # inline, on the caller's connection: a test transaction is invisible to threads
        for delivery_id in ids:
            _send_safely(delivery_id)
        return
    with ThreadPoolExecutor(max_workers=WORKERS) as pool:
        list(pool.map(_send_safely, ids))


def _send_safely(delivery_id) -> None:
    try:
        _send_one(delivery_id)
    except Exception:
        logger.exception("Push delivery %s failed", delivery_id)
    finally:
        if not settings.PUSH_SYNC:
            connection.close()  # each worker thread owns its connection


def deliver_now(notification_id) -> None:
    """Send a notification from the calling thread (scheduler, management commands)."""
    _deliver(notification_id)


def queue(notification: PushNotification, user_guids) -> int:
    """Create a delivery per device of `user_guids`. Returns the number of devices."""
    subscriptions = list(PushSubscription.objects.filter(user_id__in=list(user_guids)))
    PushDelivery.objects.bulk_create([
        PushDelivery(notification=notification, subscription=s, device=s.device, installed=s.installed,
                     user=s.user_id)
        for s in subscriptions
    ])
    return len(subscriptions)


def dispatch(notification: PushNotification) -> None:
    """Start sending in the background (inline when `PUSH_SYNC`, for tests)."""
    if settings.PUSH_SYNC:
        _deliver(notification.id)
        return

    def run():
        try:
            _deliver(notification.id)
        finally:
            connection.close()

    threading.Thread(target=run, daemon=True).start()


def purge_expired(now=None, dry_run=False) -> dict:
    """
    Delete the notifications older than `PUSH_HISTORY_DAYS` (their deliveries go
    with them) and the devices on which the app was not opened for
    `PUSH_DEVICE_IDLE_DAYS`. Such a device registers again, silently, the next
    time the app is opened on it (usePushRebind), as long as the browser keeps
    its permission. Idempotent; returns the counts.
    """
    now = now or timezone.now()
    notifications = PushNotification.objects.filter(
        created_at__lt=now - datetime.timedelta(days=settings.PUSH_HISTORY_DAYS))
    devices = PushSubscription.objects.filter(
        last_seen_at__lt=now - datetime.timedelta(days=settings.PUSH_DEVICE_IDLE_DAYS))
    result = {
        'notifications': notifications.count(),
        'deliveries': PushDelivery.objects.filter(notification__in=notifications).count(),
        'devices': devices.count(),
    }
    if not dry_run and (result['notifications'] or result['devices']):
        notifications.delete()
        devices.delete()
        logger.info("Push retention: %s", result)
    return result
